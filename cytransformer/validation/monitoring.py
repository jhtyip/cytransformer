def evaluate_generation_results_saved_outputs_to_share_format(save_results_file: str, world_size: int, subset_of_polytopes: int | None = None, subset_of_triangs: int | None = None):
    """
    Load one set of generation outputs (polys/masks shared across ranks, per-rank
    triangulation files concatenated along the triangulation axis), optionally
    restrict to a subset, score them with parallel_monitor_perf and print the
    summary counts.
    """
    polys_masks = np.load(save_results_file+ "_poly_masks_monitoring.npy")
    polys = np.load(save_results_file+ "_polys_monitoring.npy")

    triangs = []
    for i in range(world_size):
        triangs.append(np.load(f"{save_results_file}_rank_{i}_toSave_Ts_new.npy"))

    triangs = np.concatenate(triangs, axis=1)

    print(f"Shapes of loaded arrays: polys_masks: {polys_masks.shape}, polys: {polys.shape}, triangs: {triangs.shape}")
    assert polys.shape[0] == polys_masks.shape[0] == triangs.shape[0], "Inconsistent number of polytopes/triangulations/poly_masks"
    polys = polys[:subset_of_polytopes]
    polys_masks = polys_masks[:subset_of_polytopes]
    triangs = triangs[:subset_of_polytopes, :subset_of_triangs]
    results = parallel_monitor_perf(polys, polys_masks, triangs)
    # Drop the bulky per-triangulation boolean matrix before printing the summary.
    printable_results = {k: v for k, v in results.items() if k != "FRST_indices"}
    print("Results:", printable_results)



