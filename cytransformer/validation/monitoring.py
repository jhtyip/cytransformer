"""
Evaluation / monitoring of triangulations generated by the model.

This module turns the raw ``.npy`` outputs that a (possibly multi-rank,
multi-epoch) generation run dumps to disk into summary statistics: how many of
the generated triangulations are geometrically valid (via check_valid) and how
many are genuine FRSTs / FSTs / RSTs / STs (via check_FRST, using CYTools).

Layering:
  - ``monitor_perf`` is the core scorer for one batch of (polytope,
    triangulations) and combines both checks, also flagging any triangulation
    that CYTools calls FRST yet the geometric check rejects (a consistency
    alarm).
  - ``parallel_monitor_perf`` shards that work across CPU processes.
  - The ``evaluate_*`` / ``load_*`` / ``find_*`` helpers locate, merge and feed
    the per-rank/per-epoch output files into the scorer and persist results.
"""

